-- 默认规则集 v1 在首次加载时由插件写入（内容见 src/default_ruleset.json）。

CREATE TABLE rulesets (
    version        integer PRIMARY KEY CHECK (version > 0),
    status         text NOT NULL CHECK (status IN ('draft','active','retired')),
    definition     jsonb NOT NULL CHECK (octet_length(definition::text) <= 65536),
    checksum       text NOT NULL,
    based_on       integer,
    note           text CHECK (char_length(note) <= 500),
    created_by     bigint,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now(),
    activated_at   timestamptz,
    activated_by   bigint
);
CREATE UNIQUE INDEX rulesets_active_key ON rulesets ((true)) WHERE status = 'active';

CREATE TABLE evidence (
    id            bigint GENERATED BY DEFAULT AS IDENTITY,
    occurred_at   timestamptz NOT NULL,
    user_id       bigint NOT NULL,
    torrent_id    bigint,
    source        text NOT NULL CHECK (source ~ '^(accounting|anticheat|manual|plugin:[a-z][a-z0-9-]{1,31})$'),
    kind          text NOT NULL CHECK (char_length(kind) <= 64),
    severity      text CHECK (severity IN ('low','medium','high')),
    hits          integer NOT NULL DEFAULT 1 CHECK (hits >= 1),
    details       jsonb NOT NULL DEFAULT '{}' CHECK (octet_length(details::text) <= 4096),
    external_ref  text NOT NULL CHECK (char_length(external_ref) <= 160),
    details_hash  text,
    verdict       text CHECK (verdict IN ('confirmed','false_positive')),
    note          text CHECK (char_length(note) <= 1000),
    created_by    bigint,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (occurred_at, id)
) PARTITION BY RANGE (occurred_at);
CREATE UNIQUE INDEX evidence_source_ref_key ON evidence (source, external_ref, occurred_at);
CREATE INDEX evidence_user_time_idx ON evidence (user_id, occurred_at DESC, id DESC);
CREATE INDEX evidence_torrent_kind_idx ON evidence (torrent_id, kind, occurred_at DESC) WHERE torrent_id IS NOT NULL;
CREATE INDEX evidence_created_at_idx ON evidence (created_at);

CREATE TABLE user_risk (
    user_id            bigint PRIMARY KEY,
    score              smallint NOT NULL DEFAULT 0 CHECK (score BETWEEN 0 AND 100),
    shadow_score       smallint NOT NULL DEFAULT 0 CHECK (shadow_score BETWEEN 0 AND 100),
    peak_score         smallint NOT NULL DEFAULT 0,
    band               text NOT NULL DEFAULT 'none' CHECK (band IN ('none','low','watch','high','critical')),
    tags               text[] NOT NULL DEFAULT '{}',
    breakdown          jsonb NOT NULL DEFAULT '[]',
    ruleset_version    integer NOT NULL,
    open_case_id       bigint,
    transfer_blocked   boolean NOT NULL DEFAULT false,
    evidence_truncated boolean NOT NULL DEFAULT false,
    computed_at        timestamptz NOT NULL,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX user_risk_band_score_idx ON user_risk (band, score DESC) WHERE band <> 'none';
CREATE INDEX user_risk_positive_idx ON user_risk (user_id) WHERE score > 0 OR shadow_score > 0 OR open_case_id IS NOT NULL;

CREATE TABLE risk_history (
    user_id          bigint NOT NULL,
    at               timestamptz NOT NULL,
    from_band        text NOT NULL,
    to_band          text NOT NULL,
    score            smallint NOT NULL,
    ruleset_version  integer NOT NULL,
    PRIMARY KEY (user_id, at)
);

CREATE TABLE user_context (
    user_id               bigint PRIMARY KEY,
    account_created_at    timestamptz NOT NULL,
    class_id              integer NOT NULL,
    is_protected          boolean NOT NULL,
    confirmed_cases_365d  integer NOT NULL DEFAULT 0,
    warnings_90d          integer NOT NULL DEFAULT 0,
    refreshed_at          timestamptz NOT NULL
);

CREATE TABLE cases (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id            bigint NOT NULL,
    state              text NOT NULL CHECK (state IN ('open','resolved','dismissed','overturned','closed_stale','closed_user_deleted')),
    opened_reason      text NOT NULL CHECK (opened_reason IN ('score','manual','report')),
    score_at_open      smallint NOT NULL,
    score              smallint NOT NULL,
    peak_score         smallint NOT NULL,
    band               text NOT NULL,
    primary_rule       text NOT NULL,
    ruleset_version    integer NOT NULL,
    priority           integer NOT NULL DEFAULT 0,
    prior_case_id      bigint REFERENCES cases (id),
    assigned_to        bigint,
    claim_expires_at   timestamptz,
    resolution         text CHECK (resolution IN ('sanctioned','no_action','dismissed','overturned')),
    resolution_note    text CHECK (char_length(resolution_note) <= 2000),
    contributing_rules text[] NOT NULL DEFAULT '{}',
    resolved_by        bigint,
    resolved_at        timestamptz,
    appeal_deadline    timestamptz,
    purged_at          timestamptz,
    opened_by          bigint,
    opened_at          timestamptz NOT NULL DEFAULT now(),
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now(),
    version            integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX cases_user_open_key ON cases (user_id) WHERE state = 'open';
CREATE INDEX cases_queue_idx ON cases (priority DESC, opened_at, id) WHERE state = 'open';
CREATE INDEX cases_user_idx ON cases (user_id, opened_at DESC);
CREATE INDEX cases_resolved_idx ON cases (resolved_at) WHERE resolved_at IS NOT NULL;

CREATE TABLE case_evidence (
    case_id      bigint NOT NULL REFERENCES cases (id),
    evidence_id  bigint NOT NULL,
    snapshot     jsonb NOT NULL,
    added_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (case_id, evidence_id)
);

CREATE TABLE case_events (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id        bigint NOT NULL REFERENCES cases (id),
    at             timestamptz NOT NULL DEFAULT now(),
    kind           text NOT NULL CHECK (kind IN ('opened','evidence_added','band_changed','claimed','released','resolved','auto_action',
                                                 'suggestion','sanction_changed','external_override','swarm_snapshot','appeal','explained','closed')),
    actor_user_id  bigint,
    actor_plugin   text,
    data           jsonb NOT NULL DEFAULT '{}'
);
CREATE INDEX case_events_case_idx ON case_events (case_id, at);

CREATE TABLE case_notes (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id    bigint NOT NULL REFERENCES cases (id),
    author_id  bigint NOT NULL,
    text       text NOT NULL CHECK (char_length(text) BETWEEN 1 AND 2000),
    created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX case_notes_case_idx ON case_notes (case_id, created_at);

CREATE TABLE decision_requests (
    actor_key     text NOT NULL,
    key           text NOT NULL CHECK (char_length(key) BETWEEN 1 AND 128),
    request_hash  text NOT NULL,
    result        jsonb,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (actor_key, key)
);

CREATE TABLE sanctions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL,
    case_id      bigint REFERENCES cases (id),
    kind         text NOT NULL CHECK (kind IN ('warn','freeze_traffic','lock_wallet','disable_download','ban','adjust_traffic','reset_passkey')),
    state        text NOT NULL CHECK (state IN ('proposed','pending','active','suspended','expired','lifted','overturned','failed')),
    until        timestamptz,
    params       jsonb NOT NULL DEFAULT '{}',
    policy_id    text,
    decided_by   bigint,
    decided_at   timestamptz NOT NULL DEFAULT now(),
    approved_by  bigint,
    approved_at  timestamptz,
    activated_at timestamptz,
    lifted_by    bigint,
    lifted_at    timestamptz,
    lift_reason  text CHECK (char_length(lift_reason) <= 64),
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT sanctions_freeze_until_check CHECK (kind <> 'freeze_traffic' OR until IS NOT NULL)
);
CREATE INDEX sanctions_user_live_idx ON sanctions (user_id, kind) WHERE state IN ('proposed','pending','active','suspended');
CREATE INDEX sanctions_due_idx ON sanctions (until) WHERE state IN ('pending','active') AND until IS NOT NULL;
CREATE INDEX sanctions_case_idx ON sanctions (case_id);
CREATE UNIQUE INDEX sanctions_case_policy_key ON sanctions (case_id, policy_id, kind) WHERE policy_id IS NOT NULL;

CREATE TABLE effects (
    user_id          bigint NOT NULL,
    effect           text NOT NULL CHECK (effect IN ('ban','leech','freeze','wallet')),
    desired          jsonb NOT NULL,
    rev              integer NOT NULL DEFAULT 0,
    applied          jsonb,
    applied_rev      integer NOT NULL DEFAULT 0,
    ext_ref          text,
    state            text NOT NULL CHECK (state IN ('synced','pending','retrying','failed','overridden')),
    attempts         integer NOT NULL DEFAULT 0,
    next_attempt_at  timestamptz NOT NULL DEFAULT now(),
    last_error       text,
    overridden_at    timestamptz,
    updated_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, effect)
);
CREATE INDEX effects_unsynced_idx ON effects (next_attempt_at) WHERE state IN ('pending','retrying');

CREATE TABLE effect_ops (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          bigint NOT NULL,
    sanction_id      bigint REFERENCES sanctions (id),
    appeal_id        bigint,
    op               text NOT NULL CHECK (op IN ('warn_notice','sanction_notice','ban_notice','adjust','adjust_revert',
                                                 'compensate','passkey_reset','appeal_result_notice')),
    payload          jsonb NOT NULL DEFAULT '{}',
    state            text NOT NULL CHECK (state IN ('pending','retrying','done','failed','cancelled')),
    attempts         integer NOT NULL DEFAULT 0,
    next_attempt_at  timestamptz NOT NULL DEFAULT now(),
    result           jsonb,
    last_error       text,
    created_at       timestamptz NOT NULL DEFAULT now(),
    done_at          timestamptz
);
CREATE INDEX effect_ops_user_pending_idx ON effect_ops (user_id, id) WHERE state IN ('pending','retrying');
CREATE UNIQUE INDEX effect_ops_revert_key ON effect_ops (sanction_id, op) WHERE op IN ('adjust','adjust_revert','passkey_reset');

CREATE TABLE auto_action_log (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    bigint NOT NULL,
    case_id    bigint NOT NULL,
    policy_id  text NOT NULL,
    count      smallint NOT NULL,
    at         timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX auto_action_log_at_idx ON auto_action_log (at);

CREATE TABLE appeals (
    id               bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id          bigint NOT NULL REFERENCES cases (id),
    user_id          bigint NOT NULL,
    state            text NOT NULL CHECK (state IN ('submitted','in_review','upheld','reduced','overturned','withdrawn')),
    via              text NOT NULL CHECK (via IN ('session','token')),
    body             text CHECK (char_length(body) <= 4000),
    assigned_to      bigint,
    claim_expires_at timestamptz,
    decided_by       bigint,
    decided_at       timestamptz,
    decision_note    text CHECK (char_length(decision_note) <= 2000),
    created_at       timestamptz NOT NULL DEFAULT now(),
    updated_at       timestamptz NOT NULL DEFAULT now(),
    version          integer NOT NULL DEFAULT 1
);
CREATE UNIQUE INDEX appeals_case_active_key ON appeals (case_id) WHERE state IN ('submitted','in_review');
CREATE INDEX appeals_queue_idx ON appeals (created_at) WHERE state IN ('submitted','in_review');

CREATE TABLE appeal_tokens (
    token_hash  text PRIMARY KEY,
    op_id       bigint NOT NULL UNIQUE,
    case_id     bigint NOT NULL REFERENCES cases (id),
    user_id     bigint NOT NULL,
    expires_at  timestamptz NOT NULL,
    used_at     timestamptz,
    created_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE rule_stats (
    ruleset_version integer NOT NULL,
    rule_id         text NOT NULL,
    day             date NOT NULL,
    hits            integer NOT NULL DEFAULT 0,
    cases_opened    integer NOT NULL DEFAULT 0,
    confirmed       integer NOT NULL DEFAULT 0,
    dismissed       integer NOT NULL DEFAULT 0,
    overturned      integer NOT NULL DEFAULT 0,
    PRIMARY KEY (ruleset_version, rule_id, day)
);

CREATE TABLE simulations (
    id                uuid PRIMARY KEY,
    ruleset_version   integer NOT NULL REFERENCES rulesets (version),
    ruleset_checksum  text NOT NULL,
    baseline_version  integer NOT NULL,
    status            text NOT NULL CHECK (status IN ('running','done','failed','cancelled')),
    params            jsonb NOT NULL,
    cursor            bigint NOT NULL DEFAULT 0,
    totals            jsonb NOT NULL DEFAULT '{}',
    result            jsonb,
    created_by        bigint NOT NULL,
    created_at        timestamptz NOT NULL DEFAULT now(),
    finished_at       timestamptz
);
CREATE UNIQUE INDEX simulations_running_key ON simulations (ruleset_version) WHERE status = 'running';

CREATE TABLE explanations (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id       bigint NOT NULL REFERENCES cases (id),
    case_version  integer NOT NULL,
    model         text NOT NULL,
    text          text NOT NULL CHECK (char_length(text) <= 8000),
    created_by    bigint,
    created_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (case_id, case_version)
);
