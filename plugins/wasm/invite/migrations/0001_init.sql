-- invite（LLD §3.1）
CREATE TABLE accounts (
    user_id        bigint PRIMARY KEY,
    promo_classes  integer[] NOT NULL DEFAULT '{}',
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE quota_lots (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL,
    source       text NOT NULL CHECK (source IN ('level_promotion','periodic','shop','admin','initial','batch','penalty_refund','migration','service')),
    source_ref   text NOT NULL CHECK (char_length(source_ref) <= 200),
    amount       integer NOT NULL CHECK (amount > 0 AND amount <= 100000),
    remaining    integer NOT NULL,
    expires_at   timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT quota_lots_remaining_check CHECK (remaining >= 0 AND remaining <= amount)
);
CREATE UNIQUE INDEX quota_lots_source_key ON quota_lots (user_id, source, source_ref);
CREATE INDEX quota_lots_user_avail_idx ON quota_lots (user_id, expires_at) WHERE remaining > 0;
CREATE INDEX quota_lots_expiring_idx ON quota_lots (expires_at) WHERE remaining > 0 AND expires_at IS NOT NULL;

CREATE TABLE quota_ledger (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL,
    lot_id         bigint REFERENCES quota_lots (id) ON DELETE SET NULL,
    delta          integer NOT NULL CHECK (delta <> 0),
    reason         text NOT NULL CHECK (char_length(reason) <= 64),
    ref            text CHECK (char_length(ref) <= 200),
    balance_after  integer NOT NULL CHECK (balance_after >= 0),
    actor_id       bigint,
    note           text CHECK (char_length(note) <= 500),
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX quota_ledger_user_idx ON quota_ledger (user_id, id DESC);
CREATE INDEX quota_ledger_created_idx ON quota_ledger (created_at);

CREATE TABLE invites (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind              text NOT NULL CHECK (kind IN ('personal','system','campaign')),
    source            text NOT NULL CHECK (source IN ('user','admin','interview','application','api','campaign')),
    code_hash         bytea NOT NULL CHECK (octet_length(code_hash) = 32),
    code_hint         text NOT NULL CHECK (char_length(code_hint) = 4),
    issue_key_hash    bytea NOT NULL CHECK (octet_length(issue_key_hash) = 32),
    inviter_id        bigint,
    issued_by         bigint,
    issued_by_plugin  text,
    status            text NOT NULL DEFAULT 'active' CHECK (status IN ('active','exhausted','revoked','expired')),
    max_uses          integer NOT NULL DEFAULT 1 CHECK (max_uses BETWEEN 1 AND 100000),
    use_count         integer NOT NULL DEFAULT 0 CHECK (use_count >= 0),
    expires_at        timestamptz NOT NULL,
    email_hmac        bytea CHECK (email_hmac IS NULL OR octet_length(email_hmac) = 32),
    email_domain      text CHECK (char_length(email_domain) <= 253),
    username_binding  text CHECK (char_length(username_binding) <= 64),
    note              text CHECK (char_length(note) <= 200),
    lot_id            bigint REFERENCES quota_lots (id) ON DELETE SET NULL,
    refunded          boolean NOT NULL DEFAULT false,
    revoked_at        timestamptz,
    revoked_by        bigint,
    revoke_reason     text CHECK (revoke_reason IN ('user','admin','expired','user_deleted','tree_action','penalty','service')),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT invites_personal_check CHECK (kind <> 'personal' OR (inviter_id IS NOT NULL AND max_uses = 1))
);
CREATE UNIQUE INDEX invites_code_hash_key ON invites (code_hash);
CREATE UNIQUE INDEX invites_issue_key_hash_key ON invites (issue_key_hash);
CREATE INDEX invites_inviter_idx ON invites (inviter_id, created_at DESC) WHERE inviter_id IS NOT NULL;
CREATE INDEX invites_inviter_active_idx ON invites (inviter_id) WHERE status = 'active';
CREATE INDEX invites_expiring_idx ON invites (expires_at) WHERE status = 'active';
CREATE INDEX invites_admin_list_idx ON invites (created_at DESC, id DESC);

CREATE TABLE reservations (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invite_id       bigint NOT NULL REFERENCES invites (id) ON DELETE CASCADE,
    holder          text NOT NULL CHECK (char_length(holder) <= 80),
    state           text NOT NULL DEFAULT 'active' CHECK (state IN ('active','consumed','released')),
    reserved_until  timestamptz NOT NULL,
    user_id         bigint,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX reservations_active_key ON reservations (invite_id, holder) WHERE state = 'active';
CREATE INDEX reservations_invite_idx ON reservations (invite_id, state, reserved_until);
CREATE INDEX reservations_sweep_idx ON reservations (reserved_until) WHERE state = 'active';

CREATE TABLE redemptions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invite_id      bigint NOT NULL REFERENCES invites (id),
    invitee_id     bigint NOT NULL,
    inviter_id     bigint,
    event_id       uuid NOT NULL,
    over_redeemed  boolean NOT NULL DEFAULT false,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX redemptions_invitee_key ON redemptions (invitee_id);
CREATE INDEX redemptions_invite_idx ON redemptions (invite_id);
CREATE INDEX redemptions_inviter_idx ON redemptions (inviter_id, created_at DESC);

CREATE TABLE tree_edges (
    invitee_id             bigint PRIMARY KEY,
    inviter_id             bigint NOT NULL,
    invite_id              bigint REFERENCES invites (id) ON DELETE SET NULL,
    invitee_registered_at  timestamptz NOT NULL,
    purged                 boolean NOT NULL DEFAULT false,
    created_at             timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT tree_edges_self_check CHECK (invitee_id <> inviter_id)
);
CREATE INDEX tree_edges_inviter_idx ON tree_edges (inviter_id, invitee_id);

CREATE TABLE tree_closure (
    ancestor_id    bigint NOT NULL,
    descendant_id  bigint NOT NULL,
    depth          smallint NOT NULL CHECK (depth >= 0),
    PRIMARY KEY (ancestor_id, depth, descendant_id)
);
CREATE INDEX tree_closure_descendant_idx ON tree_closure (descendant_id, depth);

CREATE TABLE suspensions (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL,
    source         text NOT NULL CHECK (source IN ('penalty','admin','tree_action')),
    ref            text NOT NULL CHECK (char_length(ref) <= 100),
    reason         text CHECK (char_length(reason) <= 500),
    until          timestamptz,
    created_by     bigint,
    created_at     timestamptz NOT NULL DEFAULT now(),
    lifted_at      timestamptz,
    lifted_by      bigint,
    lifted_reason  text CHECK (char_length(lifted_reason) <= 200)
);
CREATE UNIQUE INDEX suspensions_ref_key ON suspensions (user_id, source, ref);
CREATE INDEX suspensions_active_idx ON suspensions (user_id) WHERE lifted_at IS NULL;

CREATE TABLE penalties (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id           text NOT NULL CHECK (char_length(rule_id) <= 64),
    rule_group        text NOT NULL CHECK (char_length(rule_group) <= 64),
    trigger           text NOT NULL CHECK (trigger IN ('invitee_banned','invitee_cheating')),
    trigger_event_id  uuid NOT NULL,
    invitee_id        bigint NOT NULL,
    target_user_id    bigint NOT NULL,
    depth             smallint NOT NULL CHECK (depth BETWEEN 1 AND 10),
    actions           jsonb NOT NULL,
    applied           jsonb NOT NULL DEFAULT '{}',
    state             text NOT NULL CHECK (state IN ('applied','pending_review','confirmed','reversed','exempt')),
    notified_at       timestamptz,
    reviewed_by       bigint,
    reviewed_at       timestamptz,
    review_note       text CHECK (char_length(review_note) <= 1000),
    reversed_at       timestamptz,
    reverse_reason    text CHECK (reverse_reason IN ('invitee_restored','review','admin')),
    version           integer NOT NULL DEFAULT 1,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX penalties_trigger_key ON penalties (trigger_event_id, rule_id, target_user_id);
CREATE INDEX penalties_dedupe_idx ON penalties (invitee_id, target_user_id, rule_group, created_at DESC);
CREATE INDEX penalties_target_idx ON penalties (target_user_id, created_at DESC);
CREATE INDEX penalties_review_idx ON penalties (created_at) WHERE state = 'pending_review';

CREATE TABLE invitee_bans (
    invitee_id  bigint NOT NULL,
    banned_at   timestamptz NOT NULL,
    event_id    uuid NOT NULL,
    PRIMARY KEY (invitee_id, banned_at)
);

CREATE TABLE user_notes (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL,
    note        text NOT NULL CHECK (char_length(note) <= 1000),
    job_id      uuid,
    created_by  bigint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX user_notes_user_idx ON user_notes (user_id, created_at DESC);

CREATE TABLE idempotency (
    key         text PRIMARY KEY CHECK (char_length(key) <= 200),   -- "<caller>:<idempotency_key>"
    op          text NOT NULL,
    result      jsonb NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX idempotency_created_idx ON idempotency (created_at);

CREATE TABLE batch_jobs (
    id          uuid PRIMARY KEY,
    kind        text NOT NULL CHECK (kind IN ('batch_grant','tree_action')),
    params      jsonb NOT NULL,
    state       text NOT NULL CHECK (state IN ('running','done','failed','cancelled')),
    cursor      jsonb NOT NULL DEFAULT '{}',
    processed   bigint NOT NULL DEFAULT 0,
    total       bigint,
    error       text,
    created_by  bigint NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE daily_stats (
    day     date NOT NULL,
    metric  text NOT NULL,
    value   bigint NOT NULL,
    PRIMARY KEY (day, metric)
);

CREATE TABLE inviter_scores (
    inviter_id      bigint PRIMARY KEY,
    computed_on     date NOT NULL,
    redeemed        integer NOT NULL,
    early_banned    integer NOT NULL,
    early_ban_rate  numeric(6,4) NOT NULL,
    flagged         boolean NOT NULL,
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX inviter_scores_rank_idx ON inviter_scores (early_ban_rate DESC, redeemed DESC);
