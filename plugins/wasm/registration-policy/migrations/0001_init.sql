-- registration-policy（docs/plugins/registration-policy/03 §3 的子集）：限时开放窗口、名额占位。
-- 占位：钩子中预留（reserved，10 分钟），收到 user.registered 后确认（confirmed）；IP 类占位确认后不再关联用户。
CREATE TABLE windows (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    starts_at     timestamptz NOT NULL,
    ends_at       timestamptz NOT NULL CHECK (ends_at > starts_at),
    slots         integer CHECK (slots > 0),
    note          text CHECK (char_length(note) <= 200),
    created_by    bigint,
    cancelled_at  timestamptz,
    created_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX windows_active_idx ON windows (starts_at, ends_at) WHERE cancelled_at IS NULL;

CREATE TABLE claims (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    pool            text NOT NULL CHECK (char_length(pool) <= 80),
    holder          text,
    state           text NOT NULL CHECK (state IN ('reserved', 'confirmed', 'released')),
    reserved_until  timestamptz,
    confirmed_at    timestamptz,
    user_id         bigint,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX claims_reserved_key ON claims (pool, holder) WHERE state = 'reserved';
CREATE INDEX claims_pool_idx ON claims (pool, state);
CREATE INDEX claims_holder_idx ON claims (holder) WHERE state = 'reserved';

-- 同一池的占位串行化（固定顺序取行锁）
CREATE TABLE claim_locks (
    pool        text PRIMARY KEY,
    touched_at  timestamptz NOT NULL DEFAULT now()
);
