-- seedbox（docs/plugins/seedbox/03 §3 子集）：盒子登记与网段。IP 段属于敏感数据：用户删除登记时立即删除。
CREATE TABLE boxes (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL,
    provider       text CHECK (char_length(provider) <= 64),
    note           text CHECK (char_length(note) <= 200),
    state          text NOT NULL CHECK (state IN ('pending', 'approved', 'rejected', 'expired')),
    review_reason  text CHECK (char_length(review_reason) <= 500),
    reviewed_by    bigint,
    reviewed_at    timestamptz,
    expires_at     timestamptz,
    overlap_note   text,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX boxes_user_idx ON boxes (user_id);
CREATE INDEX boxes_state_idx ON boxes (state, created_at);

CREATE TABLE box_ranges (
    box_id   bigint NOT NULL REFERENCES boxes(id) ON DELETE CASCADE,
    user_id  bigint NOT NULL,
    cidr     cidr NOT NULL,
    PRIMARY KEY (box_id, cidr)
);
CREATE INDEX box_ranges_cidr_idx ON box_ranges USING gist (cidr inet_ops);

-- 对外视图：已批准且未过期的网段（accounting 据此标记 peer）
CREATE VIEW v_ranges WITH (security_barrier = true) AS
SELECT r.user_id, r.cidr
FROM box_ranges r JOIN boxes b ON b.id = r.box_id
WHERE b.state = 'approved' AND (b.expires_at IS NULL OR b.expires_at > now());
