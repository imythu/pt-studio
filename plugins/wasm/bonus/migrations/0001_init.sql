CREATE TABLE currencies (
    code            text PRIMARY KEY CHECK (code ~ '^[a-z][a-z0-9_]{1,15}$'),
    scale           smallint NOT NULL CHECK (scale BETWEEN 0 AND 6),
    name_term       text NOT NULL,
    source          text NOT NULL CHECK (source IN ('builtin','config')),
    external_award  boolean NOT NULL DEFAULT false,
    is_active       boolean NOT NULL DEFAULT true,
    created_at      timestamptz NOT NULL DEFAULT now(),
    updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE action_rules (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                text NOT NULL UNIQUE CHECK (code ~ '^[a-z][a-z0-9_]{1,31}$'),
    trigger             text NOT NULL CHECK (trigger IN ('torrent_approved','comment_created','topic_created',
                                                         'post_created','request_filled','subtitle_uploaded','invite_redeemed')),
    currency            text NOT NULL REFERENCES currencies (code),
    amount              bigint NOT NULL CHECK (amount > 0),
    daily_count_limit   integer NOT NULL DEFAULT 0,
    daily_amount_limit  bigint NOT NULL DEFAULT 0,
    is_enabled          boolean NOT NULL DEFAULT true,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE action_awards (
    id                 bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id            bigint NOT NULL REFERENCES action_rules (id),
    user_id            bigint NOT NULL,
    ref                text NOT NULL CHECK (char_length(ref) <= 64),
    event_id           uuid NOT NULL,
    currency           text NOT NULL,
    amount             bigint NOT NULL,
    state              text NOT NULL CHECK (state IN ('pending','awarded','failed','clawed','clawback_pending','clawback_expired')),
    entry_id           uuid,
    error_code         text,
    created_at         timestamptz NOT NULL DEFAULT now(),
    updated_at         timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX action_awards_rule_ref_key ON action_awards (rule_id, ref);

CREATE TABLE action_daily (
    user_id  bigint NOT NULL,
    rule_id  bigint NOT NULL,
    day      date NOT NULL,
    count    integer NOT NULL,
    amount   bigint NOT NULL,
    PRIMARY KEY (user_id, rule_id, day)
);

CREATE TABLE service_awards (
    caller_plugin    text NOT NULL,
    idempotency_key  text NOT NULL CHECK (char_length(idempotency_key) BETWEEN 1 AND 128),
    request_hash     text NOT NULL,
    user_id          bigint NOT NULL,
    currency         text NOT NULL,
    amount           bigint NOT NULL,
    reason           text NOT NULL,
    entry_id         uuid,
    created_at       timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (caller_plugin, idempotency_key)
);
