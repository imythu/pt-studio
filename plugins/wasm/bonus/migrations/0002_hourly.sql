-- 0002：规则集、种子镜像、用户小时、应计与入账（bonus 03 §3.1 子集）。

CREATE TABLE rule_sets (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         text NOT NULL CHECK (char_length(name) <= 100),
    description  text CHECK (char_length(description) <= 20000),
    preset       text,
    draft        jsonb NOT NULL,
    draft_rev    integer NOT NULL DEFAULT 1,
    is_archived  boolean NOT NULL DEFAULT false,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE rule_versions (
    version         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_set_id     bigint NOT NULL REFERENCES rule_sets (id),
    definition      jsonb NOT NULL,
    effective_from  timestamptz NOT NULL,
    is_revoked      boolean NOT NULL DEFAULT false,
    note            text CHECK (char_length(note) <= 500),
    published_at    timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX rule_versions_effective_idx ON rule_versions (effective_from DESC) WHERE NOT is_revoked;

CREATE TABLE torrent_facts (
    torrent_id        bigint PRIMARY KEY,
    size              bigint NOT NULL DEFAULT 0,
    type_id           text,
    uploader_id       bigint,
    is_anonymous      boolean NOT NULL DEFAULT false,
    source_created_at timestamptz,
    status            text,
    is_deleted        boolean NOT NULL DEFAULT false,
    leechers          integer NOT NULL DEFAULT 0,
    completed         integer NOT NULL DEFAULT 0,
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE torrent_tags (
    torrent_id  bigint NOT NULL,
    tag         text NOT NULL CHECK (char_length(tag) <= 64),
    PRIMARY KEY (torrent_id, tag)
);

CREATE TABLE snapshot_parts (
    user_id        bigint NOT NULL,
    period_start   timestamptz NOT NULL,
    batch_id       uuid NOT NULL,
    part           smallint NOT NULL,
    parts          smallint NOT NULL CHECK (parts BETWEEN 2 AND 1000),
    rule_version   integer NOT NULL,
    partial        jsonb NOT NULL,
    created_at     timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, period_start, part)
);

CREATE TABLE user_hours (
    period_start    timestamptz NOT NULL,
    user_id         bigint NOT NULL,
    rule_version    integer NOT NULL,
    torrent_count   integer NOT NULL,
    total_size      bigint NOT NULL,
    terms           jsonb NOT NULL,
    amounts         jsonb NOT NULL,
    skipped_reason  text CHECK (skipped_reason IN ('paused','user_banned','user_deleted','user_pending','leech_disabled','user_missing')),
    flags           jsonb NOT NULL DEFAULT '{}',
    source          text NOT NULL CHECK (source IN ('live','replay')),
    created_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (period_start, user_id)
) PARTITION BY RANGE (period_start);
-- 早于预建分区的小时（如回填）落入默认分区
CREATE TABLE user_hours_default PARTITION OF user_hours DEFAULT;

CREATE TABLE accruals (
    user_id       bigint NOT NULL,
    currency      text NOT NULL REFERENCES currencies (code),
    period_start  timestamptz NOT NULL,
    amount        bigint NOT NULL CHECK (amount > 0),
    posting_id    bigint,
    created_at    timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, currency, period_start)
);
CREATE INDEX accruals_pending_idx ON accruals (currency, period_start) WHERE posting_id IS NULL;

CREATE TABLE postings (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    currency      text NOT NULL REFERENCES currencies (code),
    cutoff        timestamptz NOT NULL,
    state         text NOT NULL CHECK (state IN ('open','submitting','done','done_with_failures')),
    item_count    integer NOT NULL DEFAULT 0,
    total_amount  bigint NOT NULL DEFAULT 0,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    UNIQUE (currency, cutoff)
);

CREATE TABLE posting_items (
    posting_id  bigint NOT NULL REFERENCES postings (id),
    user_id     bigint NOT NULL,
    amount      bigint NOT NULL CHECK (amount > 0),
    hours       integer NOT NULL,
    state       text NOT NULL DEFAULT 'pending' CHECK (state IN ('pending','done','failed','voided')),
    entry_id    uuid,
    attempts    smallint NOT NULL DEFAULT 0,
    error_code  text,
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (posting_id, user_id)
);
