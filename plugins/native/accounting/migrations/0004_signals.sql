-- 0004：基础信号（03 §1.4、§1.10）、交叉校验用的小时明细、swarm 视图（anticheat 案件快照）。

CREATE TABLE signals (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL,
    torrent_id  bigint NOT NULL DEFAULT 0,          -- 0 = 与种子无关
    signal      text NOT NULL CHECK (signal IN ('cross_check_mismatch','speed_exceeded','peer_not_in_swarm',
                                                'negative_delta','counter_jump','client_not_allowed')),
    severity    text NOT NULL CHECK (severity IN ('low','medium','high')),
    hits        integer NOT NULL DEFAULT 1 CHECK (hits >= 1),
    details     jsonb NOT NULL DEFAULT '{}' CHECK (octet_length(details::text) <= 4096),
    first_at    timestamptz NOT NULL,
    last_at     timestamptz NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX signals_user_id_idx ON signals (user_id, created_at DESC, id DESC);
CREATE INDEX signals_created_idx ON signals (created_at);

-- 同一 (用户, 种子, 信号) 在去重周期内只发布一次事件，其余累加 hits；严重度升级时再次发布
CREATE TABLE signal_dedupe (
    user_id     bigint NOT NULL,
    torrent_id  bigint NOT NULL,
    signal      text NOT NULL,
    severity    text NOT NULL,
    until       timestamptz NOT NULL,
    signal_id   bigint NOT NULL,
    hits        integer NOT NULL DEFAULT 1,
    PRIMARY KEY (user_id, torrent_id, signal)
);
CREATE INDEX signal_dedupe_until_idx ON signal_dedupe (until);

-- 每小时每 (种子, 用户) 的原始流量（交叉校验）
CREATE TABLE torrent_user_hourly (
    hour        integer NOT NULL,                   -- H(t) = floor(t / 3600)
    torrent_id  bigint NOT NULL,
    user_id     bigint NOT NULL,
    up_raw      bigint NOT NULL DEFAULT 0,
    down_raw    bigint NOT NULL DEFAULT 0,
    PRIMARY KEY (hour, torrent_id, user_id)
);

CREATE TABLE cross_check_runs (
    hour         integer PRIMARY KEY,
    torrents     integer NOT NULL DEFAULT 0,
    signals      integer NOT NULL DEFAULT 0,
    finished_at  timestamptz NOT NULL DEFAULT now()
);

-- 种子的活跃 peer 与该用户在种子上的累计流量（不含 IP、端口、peer_id）
CREATE VIEW v_swarm_peers WITH (security_barrier = true) AS
SELECT p.torrent_id, p.user_id, p.is_seeder, p.client_prefix, p.first_seen_at, p.last_announce_at,
       coalesce(s.uploaded_raw, 0) AS uploaded_raw, coalesce(s.downloaded_raw, 0) AS downloaded_raw
FROM peers p
LEFT JOIN snatches s ON s.user_id = p.user_id AND s.torrent_id = p.torrent_id
WHERE p.is_active AND p.last_announce_at > now() - interval '1 hour';
