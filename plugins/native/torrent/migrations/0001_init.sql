CREATE VIEW v_torrent_public WITH (security_barrier = true) AS
SELECT id, group_id, type_id, title, size, status, created_at,
       CASE WHEN is_anonymous THEN NULL ELSE uploader_id END AS uploader_id
FROM torrents WHERE deleted_at IS NULL;

CREATE VIEW v_torrent_tracker WITH (security_barrier = true) AS
SELECT id, info_hash_v1, info_hash_v2, size, status, uploader_id, file_version, deleted_at, delete_reason, updated_at
FROM torrents;

CREATE VIEW v_torrent_fields WITH (security_barrier = true) AS
SELECT id, group_id, type_id, category_id, fields, release_group_id, updated_at
FROM torrents WHERE deleted_at IS NULL;

CREATE VIEW v_torrent_fingerprint WITH (security_barrier = true) AS
SELECT id, content_fp, size, status FROM torrents WHERE deleted_at IS NULL AND content_fp IS NOT NULL;

CREATE VIEW v_uploader_counts WITH (security_barrier = true) AS
SELECT uploader_id AS user_id,
       count(*) FILTER (WHERE status = 'approved') AS approved_count,
       count(*) AS total_count,
       coalesce(sum(size) FILTER (WHERE status = 'approved'), 0) AS approved_size
FROM torrents WHERE deleted_at IS NULL AND uploader_id IS NOT NULL GROUP BY uploader_id;
