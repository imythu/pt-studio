CREATE TABLE groups (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    type_id        text NOT NULL CHECK (char_length(type_id) <= 32),
    group_key      text NOT NULL CHECK (char_length(group_key) <= 256),
    title          text NOT NULL CHECK (char_length(title) <= 300),
    year           integer CHECK (year BETWEEN 1800 AND 2200),
    fields         jsonb NOT NULL DEFAULT '{}' CHECK (pg_column_size(fields) <= 65536),
    torrent_count  integer NOT NULL DEFAULT 0,
    last_upload_at timestamptz,
    merged_into    bigint REFERENCES groups (id),
    deleted_at     timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now(),
    updated_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX groups_type_id_group_key_key ON groups (type_id, group_key)
    WHERE deleted_at IS NULL AND merged_into IS NULL;

CREATE TABLE torrents (
    id                bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    group_id          bigint REFERENCES groups (id),
    type_id           text NOT NULL CHECK (char_length(type_id) <= 32),
    category_id       integer,
    release_group_id  integer,
    title             text NOT NULL CHECK (char_length(title) BETWEEN 1 AND 300),
    subtitle          text CHECK (char_length(subtitle) <= 300),
    description       text NOT NULL DEFAULT '' CHECK (char_length(description) <= 65536),
    mediainfo         text CHECK (char_length(mediainfo) <= 131072),
    fields            jsonb NOT NULL DEFAULT '{}' CHECK (pg_column_size(fields) <= 65536),
    size              bigint NOT NULL CHECK (size >= 0),
    file_count        integer NOT NULL CHECK (file_count >= 1),
    piece_length      integer NOT NULL,
    meta_version      smallint NOT NULL CHECK (meta_version IN (1, 2, 3)),
    info_hash_v1      bytea CHECK (octet_length(info_hash_v1) = 20),
    info_hash_v2      bytea CHECK (octet_length(info_hash_v2) = 32),
    content_fp        bytea CHECK (octet_length(content_fp) = 20),
    file_version      integer NOT NULL DEFAULT 1,
    blob_key          text NOT NULL,
    has_nfo           boolean NOT NULL DEFAULT false,
    uploader_id       bigint,
    uploader_purged   boolean NOT NULL DEFAULT false,
    is_anonymous      boolean NOT NULL DEFAULT false,
    status            text NOT NULL CHECK (status IN ('candidate','pending','approved','rejected','disabled','deleted')),
    status_reason     text CHECK (char_length(status_reason) <= 500),
    deleted_at        timestamptz,
    delete_reason     text CHECK (char_length(delete_reason) <= 32),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now(),
    version           integer NOT NULL DEFAULT 1,
    CONSTRAINT torrents_hash_present_check CHECK (info_hash_v1 IS NOT NULL OR info_hash_v2 IS NOT NULL),
    CONSTRAINT torrents_deleted_check CHECK ((status = 'deleted') = (deleted_at IS NOT NULL))
);
CREATE UNIQUE INDEX torrents_info_hash_v1_live_key ON torrents (info_hash_v1) WHERE deleted_at IS NULL AND info_hash_v1 IS NOT NULL;
CREATE UNIQUE INDEX torrents_info_hash_v2_live_key ON torrents (info_hash_v2) WHERE deleted_at IS NULL AND info_hash_v2 IS NOT NULL;
CREATE INDEX torrents_content_fp_idx ON torrents (content_fp) WHERE content_fp IS NOT NULL;
CREATE INDEX torrents_uploader_id_idx ON torrents (uploader_id, created_at DESC, id DESC);
CREATE INDEX torrents_group_id_idx ON torrents (group_id) WHERE group_id IS NOT NULL;

CREATE TABLE torrent_file_versions (
    torrent_id    bigint NOT NULL REFERENCES torrents (id),
    file_version  integer NOT NULL,
    info_hash_v1  bytea CHECK (octet_length(info_hash_v1) = 20),
    info_hash_v2  bytea CHECK (octet_length(info_hash_v2) = 32),
    blob_key      text NOT NULL,
    size          bigint NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    replaced_at   timestamptz,
    PRIMARY KEY (torrent_id, file_version)
);

