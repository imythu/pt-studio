-- WebAuthn 凭据（identity 03 §1.4）：公钥存 COSE 原始字节；user handle 为每用户随机 32 字节（不用数字 ID）。
CREATE TABLE webauthn_user_handles (
    user_id      bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    user_handle  bytea NOT NULL UNIQUE
);

CREATE TABLE webauthn_credentials (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    credential_id  bytea NOT NULL CHECK (octet_length(credential_id) <= 1023),
    public_key     bytea NOT NULL,
    alg            integer NOT NULL,
    sign_count     bigint NOT NULL DEFAULT 0,
    name           text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 64),
    -- 可发现凭据（resident key）：可用于免密码登录
    discoverable   boolean NOT NULL DEFAULT false,
    aaguid         uuid,
    last_used_at   timestamptz,
    created_at     timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX webauthn_credentials_credential_id_key ON webauthn_credentials (credential_id);
CREATE INDEX webauthn_credentials_user_id_idx ON webauthn_credentials (user_id);
