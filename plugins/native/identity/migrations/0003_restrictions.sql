-- 限制与有效状态（identity 03 §1.6）。幂等由“同用户同类型同来源只有一条生效限制”保证（upsert）。
CREATE TABLE restrictions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind         text NOT NULL CHECK (kind IN ('ban','leech_disabled','pending')),
    source       text NOT NULL CHECK (char_length(source) <= 64),
    reason_code  text NOT NULL CHECK (char_length(reason_code) <= 64),
    note         text CHECK (char_length(note) <= 1000),
    until        timestamptz,
    created_by   bigint,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now(),
    updated_by   bigint,
    lifted_at    timestamptz,
    lifted_by    bigint,
    lift_reason  text CHECK (char_length(lift_reason) <= 1000)
);
CREATE UNIQUE INDEX restrictions_active_key ON restrictions (user_id, kind, source) WHERE lifted_at IS NULL;
CREATE INDEX restrictions_until_idx ON restrictions (until) WHERE lifted_at IS NULL AND until IS NOT NULL;
CREATE INDEX restrictions_user_id_idx ON restrictions (user_id, created_at DESC);
