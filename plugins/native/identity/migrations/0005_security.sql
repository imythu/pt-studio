-- 登录限流之外的风险数据（identity 03 §1.9、§3）：设备、IP 记录、安全事件。
-- 偏差：ip_log / security_events 不分区（内核的分区维护没有保留期删除），由 cron ip_retention 截断与按批删除。

ALTER TABLE sessions
    ADD COLUMN device_id bigint,
    ADD COLUMN last_ip   inet;

CREATE TABLE devices (
    id             bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    device_mac     bytea NOT NULL CHECK (octet_length(device_mac) = 32),
    ua_summary     text CHECK (char_length(ua_summary) <= 128),
    first_seen_at  timestamptz NOT NULL DEFAULT now(),
    last_seen_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX devices_user_device_key ON devices (user_id, device_mac);

-- 同一用户、同一 IP、同一来源每月一行；跨月产生新行
CREATE TABLE ip_log (
    user_id           bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    ip                inet NOT NULL,
    ip_mac            bytea NOT NULL,
    source            text NOT NULL CHECK (source IN ('login', 'session', 'token', 'register')),
    truncated         boolean NOT NULL DEFAULT false,
    hits              integer NOT NULL DEFAULT 1,
    first_seen_month  date NOT NULL,
    first_seen_at     timestamptz NOT NULL DEFAULT now(),
    last_seen_at      timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, ip_mac, source, first_seen_month)
);
CREATE INDEX ip_log_ip_mac_idx ON ip_log (ip_mac, last_seen_at DESC);
CREATE INDEX ip_log_ip_idx ON ip_log USING gist (ip inet_ops);
CREATE INDEX ip_log_user_idx ON ip_log (user_id, last_seen_at DESC);
CREATE INDEX ip_log_truncate_idx ON ip_log (last_seen_at) WHERE NOT truncated;

CREATE TABLE security_events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    kind        text NOT NULL CHECK (char_length(kind) <= 48),
    -- 不含敏感值：IP 只存截断形式（IPv4 /24、IPv6 /48）
    details     jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX security_events_user_idx ON security_events (user_id, created_at DESC);
CREATE INDEX security_events_created_idx ON security_events (created_at);
