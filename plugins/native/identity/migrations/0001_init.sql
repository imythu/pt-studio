-- identity 0001（docs/plugins/identity/03 §3.1 的 P1 子集）。search_path = identity。
-- 评审 R1 U-1（推荐方案）：邮箱以应用层密钥加密存储（email_enc），唯一性用 HMAC（email_mac），不提供明文邮箱视图。

CREATE TABLE users (
    id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username            text NOT NULL CHECK (char_length(username) BETWEEN 1 AND 64),
    username_canonical  text NOT NULL,
    class_id            integer NOT NULL DEFAULT 0 CHECK (class_id >= 0),
    status              text NOT NULL DEFAULT 'active'
                        CHECK (status IN ('active','pending','leech_disabled','banned','deleted')),
    status_version      integer NOT NULL DEFAULT 1,
    auth_version        integer NOT NULL DEFAULT 1,
    title               text CHECK (char_length(title) <= 30),
    avatar_url          text CHECK (char_length(avatar_url) <= 512),
    bio                 text CHECK (char_length(bio) <= 2000),
    locale              text NOT NULL DEFAULT 'zh-CN' CHECK (char_length(locale) <= 16),
    registration_mode   text NOT NULL DEFAULT 'open'
                        CHECK (registration_mode IN ('open','invite','application','admin','import')),
    inviter_id          bigint,
    tags                text[] NOT NULL DEFAULT '{}',
    last_seen_at        timestamptz,
    created_at          timestamptz NOT NULL DEFAULT now(),
    updated_at          timestamptz NOT NULL DEFAULT now(),
    deleted_at          timestamptz
);
CREATE UNIQUE INDEX users_username_canonical_key ON users (username_canonical);
CREATE INDEX users_status_idx ON users (status) WHERE status <> 'active';
CREATE INDEX users_class_id_idx ON users (class_id);
CREATE INDEX users_created_at_idx ON users (created_at, id);

CREATE TABLE user_emails (
    user_id      bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    email_enc    bytea NOT NULL,
    email_mac    bytea NOT NULL CHECK (octet_length(email_mac) = 32),
    email_domain text NOT NULL CHECK (char_length(email_domain) <= 253),
    verified_at  timestamptz,
    created_at   timestamptz NOT NULL DEFAULT now(),
    updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX user_emails_email_mac_key ON user_emails (email_mac);
CREATE INDEX user_emails_email_domain_idx ON user_emails (email_domain);

CREATE TABLE user_passwords (
    user_id      bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    algo         text NOT NULL CHECK (algo IN ('argon2id','legacy_nexus_sha256','legacy_nexus_md5','legacy_bcrypt','none')),
    phc          text,
    legacy_hash  text,
    salt         text,
    changed_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT user_passwords_algo_check2 CHECK ((algo = 'argon2id') = (phc IS NOT NULL))
);

CREATE TABLE passkeys (
    user_id      bigint PRIMARY KEY REFERENCES users(id) ON DELETE CASCADE,
    passkey_enc  bytea,
    passkey_mac  bytea CHECK (octet_length(passkey_mac) = 32),
    version      integer NOT NULL DEFAULT 1,
    revoked_at   timestamptz,
    updated_at   timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT passkeys_pair_check CHECK ((passkey_enc IS NULL) = (passkey_mac IS NULL))
);
CREATE UNIQUE INDEX passkeys_passkey_mac_key ON passkeys (passkey_mac) WHERE passkey_mac IS NOT NULL;

CREATE TABLE sessions (
    id                   uuid PRIMARY KEY,
    user_id              bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash           bytea NOT NULL CHECK (octet_length(token_hash) = 32),
    remember             boolean NOT NULL DEFAULT false,
    method               text NOT NULL,
    two_factor_at        timestamptz,
    reauth_at            timestamptz,
    ua_summary           text CHECK (char_length(ua_summary) <= 128),
    ip_mac               bytea,
    auth_version         integer NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    last_seen_at         timestamptz NOT NULL DEFAULT now(),
    idle_expires_at      timestamptz NOT NULL,
    absolute_expires_at  timestamptz NOT NULL,
    revoked_at           timestamptz,
    revoked_reason       text
);
CREATE UNIQUE INDEX sessions_token_hash_key ON sessions (token_hash);
CREATE INDEX sessions_user_id_idx ON sessions (user_id) WHERE revoked_at IS NULL;
CREATE INDEX sessions_gc_idx ON sessions (absolute_expires_at);

-- ========== RBAC ==========
CREATE TABLE permissions (
    name              text PRIMARY KEY CHECK (name ~ '^[a-z][a-z0-9-]*(\.[a-z][a-z0-9_]*){1,2}$'),
    plugin_id         text NOT NULL,
    description_term  text NOT NULL,
    default_roles     text[] NOT NULL DEFAULT '{}',
    orphan            boolean NOT NULL DEFAULT false,
    first_seen_at     timestamptz NOT NULL DEFAULT now(),
    last_seen_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE roles (
    name          text PRIMARY KEY CHECK (name ~ '^([a-z]+|[a-z][a-z0-9-]*:[a-z0-9_]{1,48})$'),
    kind          text NOT NULL CHECK (kind IN ('builtin','plugin','custom')),
    owner_plugin  text,
    rank          smallint,
    name_term     text NOT NULL,
    created_at    timestamptz NOT NULL DEFAULT now(),
    updated_at    timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT roles_rank_check CHECK ((kind = 'builtin') = (rank IS NOT NULL))
);

CREATE TABLE role_permissions (
    role        text NOT NULL REFERENCES roles(name) ON DELETE CASCADE,
    permission  text NOT NULL REFERENCES permissions(name) ON DELETE CASCADE,
    granted_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (role, permission)
);

CREATE TABLE user_roles (
    user_id     bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    role        text NOT NULL REFERENCES roles(name) ON DELETE CASCADE,
    expires_at  timestamptz,
    granted_by  text NOT NULL,
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, role)
);
CREATE INDEX user_roles_role_idx ON user_roles (role);

