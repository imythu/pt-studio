-- 客户端规则（LLD §3.1）：有序规则 + 默认动作；保存时整体替换并导出到 trk:clients
CREATE TABLE client_ruleset (
    id              smallint PRIMARY KEY CHECK (id = 1),
    -- 0 表示尚未从旧版设置迁移
    version         integer NOT NULL DEFAULT 0,
    default_action  text NOT NULL DEFAULT 'deny' CHECK (default_action IN ('allow','deny')),
    -- 最近写入 trk:clients 的 ver
    exported_ver    bigint,
    updated_at      timestamptz NOT NULL DEFAULT now(),
    updated_by      bigint
);
INSERT INTO client_ruleset (id) VALUES (1) ON CONFLICT DO NOTHING;

CREATE TABLE client_rules (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    position    integer NOT NULL,
    name        text NOT NULL CHECK (char_length(name) BETWEEN 1 AND 64),
    action      text NOT NULL CHECK (action IN ('allow','deny')),
    pid_prefix  text CHECK (char_length(pid_prefix) <= 60),
    pid_regex   text CHECK (char_length(pid_regex) <= 256),
    min_ver     text CHECK (min_ver ~ '^\d+(\.\d+){0,3}$'),
    max_ver     text CHECK (max_ver ~ '^\d+(\.\d+){0,3}$'),
    ua_prefix   text CHECK (char_length(ua_prefix) <= 64),
    ua_regex    text CHECK (char_length(ua_regex) <= 256),
    enabled     boolean NOT NULL DEFAULT true,
    note        text NOT NULL DEFAULT '' CHECK (char_length(note) <= 500),
    created_at  timestamptz NOT NULL DEFAULT now(),
    updated_at  timestamptz NOT NULL DEFAULT now(),
    updated_by  bigint,
    CONSTRAINT client_rules_position_key UNIQUE (position),
    CONSTRAINT client_rules_condition_check CHECK (num_nonnulls(pid_prefix, pid_regex, ua_prefix, ua_regex) >= 1)
);
