-- ledger 0002：批量发放（docs/plugins/ledger/03 §1.12）。search_path = ledger。
CREATE TABLE grant_batches (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    request_key     text NOT NULL UNIQUE,                 -- 创建请求的幂等键（重复提交返回同一批）
    currency        text NOT NULL REFERENCES currencies (code),
    amount          bigint NOT NULL CHECK (amount > 0),   -- 每人数量（最小单位）
    memo            text NOT NULL CHECK (char_length(memo) BETWEEN 1 AND 200),
    target          jsonb NOT NULL,                       -- 发放对象条件（快照，展示用）
    notify          boolean NOT NULL,
    subject         text CHECK (char_length(subject) <= 120),
    body            text CHECK (char_length(body) <= 5000),
    state           text NOT NULL CHECK (state IN ('granting','notifying','done')),
    total           integer NOT NULL DEFAULT 0,
    granted         integer NOT NULL DEFAULT 0,
    failed          integer NOT NULL DEFAULT 0,
    notified        integer NOT NULL DEFAULT 0,
    notify_failed   integer NOT NULL DEFAULT 0,
    notify_retries  integer NOT NULL DEFAULT 0,           -- 连续可重试失败次数（站内信暂不可用时）
    last_error      text,
    created_by      bigint NOT NULL,
    created_at      timestamptz NOT NULL DEFAULT now(),
    finished_at     timestamptz
);
CREATE INDEX grant_batches_active_idx ON grant_batches (id) WHERE state <> 'done';

CREATE TABLE grant_recipients (
    batch_id       bigint NOT NULL REFERENCES grant_batches (id) ON DELETE CASCADE,
    user_id        bigint NOT NULL,
    entry_id       uuid,                                  -- 发放成功的流水
    balance_after  bigint,
    error          text,                                  -- 发放失败原因（错误码）
    granted_at     timestamptz,
    notified_at    timestamptz,
    notify_error   text,
    PRIMARY KEY (batch_id, user_id)
);
CREATE INDEX grant_recipients_pending_idx ON grant_recipients (batch_id, user_id)
    WHERE entry_id IS NULL AND error IS NULL;
