//! 从 docs/platform/catalog/*.md 生成内核内置 catalog（kernel/03 §2.1 第 5 步）。
//! 目前生成钩子点目录；其余目录随插件编码逐步加入（评审 R1 §3.2）。

use std::{env, fmt::Write as _, fs, path::PathBuf};

fn main() {
    let root =
        PathBuf::from(env::var("CARGO_MANIFEST_DIR").unwrap_or_default()).join("../../docs/platform/catalog");
    let hooks_md = root.join("hooks.md");
    println!("cargo:rerun-if-changed={}", hooks_md.display());
    let text = fs::read_to_string(&hooks_md).unwrap_or_default();

    let mut out = String::from("// @generated by build.rs from docs/platform/catalog/hooks.md\n");
    out.push_str("pub static HOOK_POINTS: &[HookPointDef] = &[\n");
    for line in text.lines() {
        let Some(row) = line.strip_prefix("| `") else {
            continue;
        };
        let cells: Vec<&str> = row.split(" | ").collect();
        if cells.len() < 7 || !cells[4].ends_with(" ms") {
            continue;
        }
        let name = cells[0].trim_end_matches('`');
        let owner = cells[1].split('（').next().unwrap_or("").trim();
        let decisions = cells[3];
        let modifiable: Vec<String> = decisions
            .split_once("modify")
            .map(|(_, rest)| backticked(rest))
            .unwrap_or_default();
        let append_only = decisions.contains("只能追加");
        let allow_modify = decisions.contains("modify");
        let timeout: u32 = cells[4].trim_end_matches(" ms").trim().parse().unwrap_or(200);
        let policy = cells[5];
        let deny = policy.starts_with("deny");
        let locked = policy.contains("锁定");
        let _ = writeln!(
            out,
            "    HookPointDef {{ name: {name:?}, owner: {owner:?}, allow_modify: {allow_modify}, modifiable: &{modifiable:?}, \
             append_only: {append_only}, timeout_ms: {timeout}, deny_on_error: {deny}, locked: {locked} }},"
        );
    }
    out.push_str("];\n");

    // 前端插槽（catalog/slots.md §2）
    let slots_md = root.join("slots.md");
    println!("cargo:rerun-if-changed={}", slots_md.display());
    let slots = fs::read_to_string(&slots_md).unwrap_or_default();
    let section = slots
        .split("## 2.")
        .nth(1)
        .unwrap_or("")
        .split("\n## ")
        .next()
        .unwrap_or("");
    out.push_str("pub static SLOTS: &[&str] = &[\n");
    for line in section.lines() {
        if let Some(row) = line.strip_prefix("| `")
            && let Some((name, _)) = row.split_once('`')
        {
            let _ = writeln!(out, "    {name:?},");
        }
    }
    out.push_str("];\n");

    // 错误码 → HTTP 状态（catalog/error-codes.md）
    let codes_md = root.join("error-codes.md");
    println!("cargo:rerun-if-changed={}", codes_md.display());
    let codes = fs::read_to_string(&codes_md).unwrap_or_default();
    out.push_str("pub static ERROR_STATUS: &[(&str, u16)] = &[\n");
    for line in codes.lines() {
        let Some(row) = line.strip_prefix("| `") else {
            continue;
        };
        let cells: Vec<&str> = row.split(" | ").collect();
        let Some(status) = cells.get(1).and_then(|c| c.trim().parse::<u16>().ok()) else {
            continue;
        };
        for code in backticked(&format!("`{}", cells[0])) {
            if code.contains('.') {
                let _ = writeln!(out, "    ({code:?}, {status}),");
            }
        }
    }
    out.push_str("];\n");
    let dest = PathBuf::from(env::var("OUT_DIR").unwrap_or_default()).join("hooks_catalog.rs");
    if let Err(e) = fs::write(&dest, out) {
        panic!("write {}: {e}", dest.display());
    }
}

fn backticked(s: &str) -> Vec<String> {
    s.split('`')
        .skip(1)
        .step_by(2)
        .map(|f| f.trim_end_matches("[]").to_owned())
        .collect()
}
